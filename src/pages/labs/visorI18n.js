import { useState, useCallback } from "react";

const STORAGE_KEY = "zrc_visor_lang";

export function useVisorLang() {
  const [lang, setLangState] = useState(() => {
    try { return localStorage.getItem(STORAGE_KEY) === "en" ? "en" : "es"; } catch { return "es"; }
  });
  const setLang = useCallback((l) => {
    setLangState(l);
    try { localStorage.setItem(STORAGE_KEY, l); } catch { /* noop */ }
  }, []);
  return [lang, setLang];
}

export function t(lang, key, vars) {
  const entry = (DICT[lang] && DICT[lang][key] !== undefined) ? DICT[lang][key] : DICT.es[key];
  if (entry === undefined) return key;
  return typeof entry === "function" ? entry(vars || {}) : entry;
}

